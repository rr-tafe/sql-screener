'use strict';
const { chromium, expect } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { pathToFileURL } = require('node:url');

(async function () {
  const root = path.resolve(__dirname, '../..');
  const moduleId = process.argv.find(value => value.startsWith('--module='))?.slice(9) || 'ci-test';
  const url = pathToFileURL(path.join(root, 'dist', moduleId + '.html')).href;
  const source = fs.readFileSync(path.join(root, 'modules', moduleId, 'solutions.sql'), 'utf8').replace(/\r\n/g, '\n');
  const parts = source.split(/--\s*(q\d+)\s*\n/i);
  const solutions = {};
  for (let index = 1; index < parts.length; index += 2) solutions[parts[index].toLowerCase()] = parts[index + 1].trim();
  const artifacts = fs.mkdtempSync(path.join(os.tmpdir(), 'sql-browser-check-'));
  const browser = await chromium.launch();
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, offline: true });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    await page.goto(url);
    await page.locator('#candidate-name').fill('Regression Candidate');
    await page.locator('#begin-btn').click();
    await expect(page.locator('#editor-q1 .cm-content')).toBeVisible();
    const editor = page.locator('#editor-q1 .cm-content');
    await editor.fill(solutions.q1);
    await editor.press('Control+Enter');
    await expect(page.locator('#status-q1')).toContainText('Passed');
    await editor.fill('NOT VALID SQL;\n' + solutions.q1);
    await editor.press('Control+Home');
    await editor.press('ArrowDown');
    await editor.press('Home');
    await editor.press('Control+Shift+End');
    await page.locator('.btn-selection[data-context="q1"]').click();
    await expect(page.locator('#status-q1')).toContainText('Edited since last run');
    await expect(page.locator('#save-status')).toContainText('Saved');
    const selectedRun = await page.evaluate(() => JSON.parse(localStorage.getItem('sql-assessment:' + BUILD_ID)).executions.q1);
    assert.equal(selectedRun.status, 'pass');
    assert.equal(selectedRun.sql, solutions.q1);
    await editor.fill(solutions.q1);
    await editor.press('Control+Enter');
    await expect(page.locator('#status-q1')).toContainText('Passed');
    await editor.fill('SELECT 999;');
    await expect(page.locator('#status-q1')).toContainText('Edited since last run');
    await page.locator('#finish-work-btn').click();
    const reportDownload = page.waitForEvent('download');
    await page.locator('#finish-download').click();
    const report = fs.readFileSync(await (await reportDownload).path(), 'utf8');
    assert.ok(report.includes('0 of '));
    assert.ok(report.includes('EDITED SINCE LAST RUN - UNGRADED'));
    assert.ok(report.includes('Previously executed SQL'));
    const jsonDownload = page.waitForEvent('download');
    await page.locator('#finish-json').click();
    const submission = JSON.parse(fs.readFileSync(await (await jsonDownload).path(), 'utf8'));
    assert.equal(submission.drafts.q1, 'SELECT 999;');
    assert.equal(submission.executions.q1.sql, solutions.q1);
    assert.equal(submission.questionStatuses.q1, 'changed');
    await page.locator('#finish-back').click();
    await page.reload();
    await page.locator('#resume-btn').click();
    await expect(editor).toContainText('SELECT 999;');
    await expect(page.locator('#status-q1')).toContainText('Edited since last run');
    await page.locator('#playground-editor .cm-content').fill('CREATE TEMP TABLE recovery_probe AS SELECT 42 AS value;');
    await page.locator('.btn-run[data-context="playground"]').click();
    await expect(page.locator('#playground-status')).toContainText('Executed');
    await editor.fill('WITH RECURSIVE numbers(value) AS (SELECT 1 UNION ALL SELECT value+1 FROM numbers) SELECT sum(value) FROM numbers;');
    await page.locator('.btn-run[data-context="q1"]').click();
    await page.locator('#cancel-query').click();
    await expect(page.locator('#status-q1')).toContainText('cancelled');
    await page.locator('#playground-editor .cm-content').fill('SELECT value FROM recovery_probe;');
    await page.locator('.btn-run[data-context="playground"]').click();
    await expect(page.locator('#playground-results tbody')).toContainText('42');
    await page.locator('.btn-run[data-context="q1"]').click();
    await expect(page.locator('#status-q1')).toContainText('timed out', { timeout: 15000 });
    await editor.fill(solutions.q1);
    await editor.press('Control+Enter');
    await expect(page.locator('#status-q1')).toContainText('Passed');
    await page.locator('.question-history summary').first().click();
    assert.ok(await page.locator('#history-q1 .attempt-row').count() >= 3);
    await page.locator('#history-q1 button').nth(1).click();
    await expect(editor).toContainText('WITH RECURSIVE');
    await editor.fill(solutions.q1);
    await editor.press('Control+Enter');
    await expect(page.locator('#status-q1')).toContainText('Passed');
    await page.locator('.question-history summary').first().click();
    const count = await page.evaluate(() => QUESTIONS_JSON.length);
    if (count > 1) {
      await page.locator('#next-question').click();
      await expect(page.locator('#section-q1')).toBeHidden();
      await page.locator('#all-view').click();
      await expect(page.locator('#section-q1')).toBeVisible();
      await page.locator('#previous-question').click();
      await page.locator('#focus-view').click();
    }
    await page.locator('#schema-search').fill('no_matching_table_12345');
    assert.equal(await page.locator('.schema-table-panel:visible').count(), 0);
    await page.locator('#schema-search').fill('');
    await page.locator('[data-table-toggle]').first().click();
    await expect(page.locator('.schema-table-preview .results-table').first()).toBeVisible();
    await page.screenshot({ path: path.join(artifacts, 'desktop.png'), fullPage: true });
    const checkpointDownload = page.waitForEvent('download');
    await page.locator('#checkpoint-btn').click();
    const checkpoint = fs.readFileSync(await (await checkpointDownload).path());
    for (const width of [390, 768]) {
      await page.setViewportSize({ width, height: 844 });
      await expect(page.locator('#checkpoint-btn')).toBeVisible();
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      await page.locator('#data-panel-toggle').click();
      await expect(page.locator('#right-panel')).toBeVisible();
      await expect(page.locator('#schema-search')).toBeVisible();
      await page.screenshot({ path: path.join(artifacts, 'data-' + width + '.png'), fullPage: true });
      await page.locator('#data-panel-toggle').click();
      await page.screenshot({ path: path.join(artifacts, 'questions-' + width + '.png'), fullPage: true });
    }
    const recoveryContext = await browser.newContext({ offline: true });
    const recoveryPage = await recoveryContext.newPage();
    await recoveryPage.goto(url);
    await recoveryPage.locator('#restore-file').setInputFiles({ name: 'checkpoint.json', mimeType: 'application/json', buffer: checkpoint });
    await expect(recoveryPage.locator('#editor-q1 .cm-content')).toContainText(solutions.q1.split('\n')[0]);
    await expect(recoveryPage.locator('#status-q1')).toContainText('Passed');
    await recoveryPage.locator('#playground-editor .cm-content').fill('SELECT value FROM recovery_probe;');
    await recoveryPage.locator('.btn-run[data-context="playground"]').click();
    await expect(recoveryPage.locator('#playground-results tbody')).toContainText('42');
    await recoveryContext.close();
    const unavailableContext = await browser.newContext({ offline: true });
    await unavailableContext.addInitScript(() => { Storage.prototype.setItem = function () { throw new DOMException('Storage disabled', 'QuotaExceededError'); }; });
    const unavailablePage = await unavailableContext.newPage();
    await unavailablePage.goto(url);
    await unavailablePage.locator('#candidate-name').fill('Storage unavailable');
    await unavailablePage.locator('#begin-btn').click();
    await expect(unavailablePage.locator('#save-status')).toContainText('Browser save unavailable');
    await expect(unavailablePage.locator('#checkpoint-btn')).toBeEnabled();
    await unavailableContext.close();
    assert.deepEqual(errors, []);
    console.log('Browser workflows passed offline: grading, stale exports, JSON, resume, cancellation, history, schema preview/search, mobile layouts, checkpoint import, unavailable storage.');
    console.log('Screenshots: ' + artifacts);
    await context.close();
  } finally {
    await browser.close();
  }
}()).catch(error => { console.error(error); process.exitCode = 1; });